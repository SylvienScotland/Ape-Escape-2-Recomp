#!/usr/bin/env python3
"""Differential test of the recompiler's COP1 (FPU) translations against a reference.

Like tools/mmi_check.py: one translated statement per distinct FPU operation the game uses is taken from
generated/output and run next to the reference semantics of the PAL port (the FPU helpers of
port/include/ps2.h and the decode of recomp/recomp.py, JackyPendrag0n/ae2-recomp, used with the
author's permission) on random register values. Compared: f0-31, ACC, the FCR31 condition bit, GPRs.

    python tools/fpu_check.py <path to ae2-recomp clone> <out dir>
"""
import glob
import os
import re
import sys

pal_dir, out_dir = sys.argv[1], sys.argv[2]
ps2h = open(os.path.join(pal_dir, 'port', 'include', 'ps2.h')).read()


def cop1(w):
    rs = (w >> 21) & 31; rt = (w >> 16) & 31
    ft = rt; fs = (w >> 11) & 31; fd = (w >> 6) & 31; fn = w & 63
    F = lambda r: 'c->f[%d].f' % r
    if rs == 0: return ('MFC1', rt and 'c->r[%d].sd[0] = (int32_t)c->f[%d].u;' % (rt, fs) or '')
    if rs == 4: return ('MTC1', 'c->f[%d].u = c->r[%d].uw[0];' % (fs, rt))
    if rs == 16:
        table = {0: ('ADD.S', '%s = FADD(%s, %s);' % (F(fd), F(fs), F(ft))),
                 1: ('SUB.S', '%s = FSUB(%s, %s);' % (F(fd), F(fs), F(ft))),
                 2: ('MUL.S', '%s = FMUL(%s, %s);' % (F(fd), F(fs), F(ft))),
                 3: ('DIV.S', '%s = FDIV(%s, %s);' % (F(fd), F(fs), F(ft))),
                 4: ('SQRT.S', '%s = FSQRT(%s);' % (F(fd), F(ft))),
                 5: ('ABS.S', 'c->f[%d].u = c->f[%d].u & 0x7fffffff;' % (fd, fs)),
                 6: ('MOV.S', 'c->f[%d].u = c->f[%d].u;' % (fd, fs)),
                 7: ('NEG.S', 'c->f[%d].u = c->f[%d].u ^ 0x80000000;' % (fd, fs)),
                 22: ('RSQRT.S', '%s = FRSQRT(%s, %s);' % (F(fd), F(fs), F(ft))),
                 24: ('ADDA.S', 'c->facc = FADD(%s, %s);' % (F(fs), F(ft))),
                 25: ('SUBA.S', 'c->facc = FSUB(%s, %s);' % (F(fs), F(ft))),
                 26: ('MULA.S', 'c->facc = FMUL(%s, %s);' % (F(fs), F(ft))),
                 28: ('MADD.S', '%s = FADD(c->facc, FMUL(%s, %s));' % (F(fd), F(fs), F(ft))),
                 29: ('MSUB.S', '%s = FSUB(c->facc, FMUL(%s, %s));' % (F(fd), F(fs), F(ft))),
                 30: ('MADDA.S', 'c->facc = FADD(c->facc, FMUL(%s, %s));' % (F(fs), F(ft))),
                 31: ('MSUBA.S', 'c->facc = FSUB(c->facc, FMUL(%s, %s));' % (F(fs), F(ft))),
                 36: ('CVT.W.S', 'c->f[%d].s = CVTWS(%s);' % (fd, F(fs))),
                 40: ('MAX.S', '%s = FMAX(%s, %s);' % (F(fd), F(fs), F(ft))),
                 41: ('MIN.S', '%s = FMIN(%s, %s);' % (F(fd), F(fs), F(ft))),
                 48: ('C.F.S', 'c->fcr31 &= ~0x800000u;'),
                 50: ('C.EQ.S', 'FCOND(FCEQ(%s, %s));' % (F(fs), F(ft))),
                 52: ('C.LT.S', 'FCOND(FCLT(%s, %s));' % (F(fs), F(ft))),
                 54: ('C.LE.S', 'FCOND(FCLE(%s, %s));' % (F(fs), F(ft)))}
        return table.get(fn)
    if rs == 20 and fn == 32:
        return ('CVT.S.W', '%s = (float)c->f[%d].s;' % (F(fd), fs))
    return None


comment = re.compile(r'^    // 0x([0-9a-f]+): 0x([0-9a-f]+)\s+(\S+)')
samples = {}
for path in sorted(glob.glob('generated/output/*.cpp')):
    lines = open(path, errors='ignore').read().splitlines()
    for i, line in enumerate(lines):
        m = comment.match(line)
        if not m:
            continue
        raw = int(m.group(2), 16)
        if raw >> 26 != 0x11:
            continue
        dec = cop1(raw)
        if not dec or not dec[1] or dec[0] in samples:
            continue
        body = []
        for line2 in lines[i + 1:]:
            if line2.startswith('    // 0x') or line2.startswith('label_') or line2.startswith('}'):
                break
            if re.match(r'^    ctx->pc = 0x[0-9a-fA-F]+u;$', line2):
                if body:
                    break
                continue
            body.append(line2)
        if body:
            samples[dec[0]] = (raw, '\n'.join(body), dec[1])

helpers = ps2h[ps2h.index('/* ---------- FPU'):]
helpers = helpers[:helpers.index('#define FCOND')] + \
    '#define FCOND(x) do { if (x) c->fcr31 |= 0x800000u; else c->fcr31 &= ~0x800000u; } while (0)\n'
os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, 'fpu_check.cpp'), 'w') as f:
    f.write('// generated by tools/fpu_check.py\n#include "ps2_runtime.h"\n#include "ps2_runtime_macros.h"\n#include <cstdio>\n#include <random>\n\n')
    f.write('namespace pal {\n#define unlikely(x) (x)\n#define likely(x) (x)\n')
    f.write('typedef union { uint64_t ud[2]; int64_t sd[2]; uint32_t uw[4]; int32_t sw[4]; float f[4]; } r128;\n')
    f.write('typedef union { float f; uint32_t u; int32_t s; } fpr_t;\n')
    f.write('struct Ctx { r128 r[32]; fpr_t f[32]; float facc; uint32_t fcr31; };\n')
    f.write(helpers)
    f.write('}\n\n')
    f.write('static void toPal(const R5900Context *ctx, pal::Ctx *c) {\n'
            '    std::memset(c, 0, sizeof(*c));\n'
            '    for (int i = 0; i < 32; ++i) { std::memcpy(&c->r[i], &ctx->r[i], 16); std::memcpy(&c->f[i], &ctx->f[i], 4); }\n'
            '    c->facc = ctx->f_acc; c->fcr31 = ctx->fcr31;\n}\n\n')
    f.write('static float rf(std::mt19937_64 &rng) {\n'
            '    const uint64_t r = rng(); if ((r & 15) == 0) return 0.0f;\n'
            '    if ((r & 63) == 1) { uint32_t u = 0x7f800000u | (uint32_t)(r >> 40); float x; std::memcpy(&x, &u, 4); return x; }\n'
            '    const float m = 1.0f + (float)((r >> 8) & 0xffffff) / 16777216.0f; const int e = (int)((r >> 32) % 40) - 20;\n'
            '    return ((r >> 4) & 1 ? -1.0f : 1.0f) * std::ldexp(m, e);\n}\n\n')
    f.write('int main() {\n    std::mt19937_64 rng(99);\n    int failures = 0;\n')
    f.write('    alignas(16) static R5900Context ctxStore; R5900Context *ctx = &ctxStore; uint8_t *rdram = nullptr; PS2Runtime *runtime = nullptr;\n'
            '    (void)rdram; (void)runtime;\n')
    for key, (raw, body, ref) in sorted(samples.items()):
        f.write('    {\n        int bad = 0; char why[256] = "";\n')
        f.write('        for (int iter = 0; iter < 20000 && !bad; ++iter) {\n')
        f.write('            std::memset(ctx, 0, sizeof(*ctx));\n')
        f.write('            for (int i = 0; i < 32; ++i) { ctx->f[i] = rf(rng); ctx->r[i] = i ? _mm_set_epi64x((long long)rng(), (long long)rng()) : _mm_setzero_si128(); }\n')
        f.write('            ctx->f_acc = rf(rng); ctx->fcr31 = (uint32_t)rng() & 0x00800000u;\n')
        f.write('            pal::Ctx refStore; pal::Ctx *c = &refStore; toPal(ctx, c);\n')
        f.write('            ' + body.replace('\n', '\n            ') + '\n')
        f.write('            { using namespace pal; ' + ref + ' }\n')
        f.write('            pal::Ctx got; toPal(ctx, &got);\n')
        f.write('            for (int r = 0; r < 32 && !bad; ++r) if (got.f[r].u != c->f[r].u) { bad = 1; std::snprintf(why, sizeof why, "f%d got %08x (%g) ref %08x (%g)", r, got.f[r].u, got.f[r].f, c->f[r].u, c->f[r].f); }\n')
        f.write('            if (!bad && std::memcmp(&got.facc, &c->facc, 4)) { bad = 1; std::snprintf(why, sizeof why, "ACC got %g ref %g", got.facc, c->facc); }\n')
        f.write('            if (!bad && ((got.fcr31 ^ c->fcr31) & 0x800000u)) { bad = 1; std::snprintf(why, sizeof why, "condition got %d ref %d", (got.fcr31 >> 23) & 1, (c->fcr31 >> 23) & 1); }\n')
        f.write('            for (int r = 1; r < 32 && !bad; ++r) if (got.r[r].ud[0] != c->r[r].ud[0]) { bad = 1; std::snprintf(why, sizeof why, "r%d got %016llx ref %016llx", r, (unsigned long long)got.r[r].ud[0], (unsigned long long)c->r[r].ud[0]); }\n')
        f.write('            if (bad) { char in[160]; std::snprintf(in, sizeof in, " | inputs fs=%%g ft=%%g acc=%%g", ctx->f[%d], ctx->f[%d], ctx->f_acc); std::strncat(why, in, sizeof why - std::strlen(why) - 1); }\n' % ((raw >> 11) & 31, (raw >> 16) & 31))
        f.write('        }\n')
        f.write('        if (bad) { ++failures; std::printf("MISMATCH %-8s %08x  %%s\\n", why); } else std::printf("ok       %s\\n");\n    }\n' % (key, raw, key))
    f.write('    std::printf("%%d of %d FPU operations differ\\n", failures);\n    return failures;\n}\n' % len(samples))
print('%d FPU operations sampled: %s' % (len(samples), ' '.join(sorted(samples))))
