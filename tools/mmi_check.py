#!/usr/bin/env python3
"""Differential test of the recompiler's MMI translations against a reference.

Collects, from the generated C++ (generated/output), one translated statement for every MMI mnemonic
the game uses, and writes a C++ program that runs each statement and the reference definition of the
instruction (the PAL port's port/include/mmi.h, JackyPendrag0n/ae2-recomp, used with the author's
permission) on the same random register values, then reports every instruction whose results differ.

    python tools/mmi_check.py <path to ae2-recomp clone> <out dir>
    (then compile <out dir>/mmi_check.cpp with the runtime's include paths and run it)
"""
import glob
import os
import re
import sys

pal_dir, out_dir = sys.argv[1], sys.argv[2]
pal_mmi = open(os.path.join(pal_dir, 'port', 'include', 'mmi.h')).read()
pal_ops = set(re.findall(r'mmi_([A-Z0-9]+)\(Ctx', pal_mmi)) | set(re.findall(r'^DEF3\(([A-Z0-9]+),', pal_mmi, re.M))

comment = re.compile(r'^    // 0x([0-9a-f]+): 0x([0-9a-f]+)\s+(\S+)')
samples = {}
for path in sorted(glob.glob('generated/output/*.cpp')):
    lines = open(path, errors='ignore').read().splitlines()
    for i, line in enumerate(lines):
        m = comment.match(line)
        if not m:
            continue
        raw = int(m.group(2), 16)
        if raw >> 26 != 0x1C:
            continue
        name = m.group(3).split('.')[0].upper()
        if name not in pal_ops:
            continue
        rs, rt, rd = (raw >> 21) & 31, (raw >> 16) & 31, (raw >> 11) & 31
        distinct = len({rs, rt, rd}) == 3 and 0 not in (rs, rt, rd)
        if name in samples and (samples[name][2] or not distinct):
            continue
        body = []
        for line2 in lines[i + 1:]:
            if line2.startswith('    // 0x') or line2.startswith('label_') or line2.startswith('}'):
                break
            if re.match(r'^    ctx->pc = 0x[0-9a-fA-F]+u;$', line2):
                if body:
                    break
                continue
            body.append(line2)
        if body:
            samples[name] = (raw, '\n'.join(body), distinct)

os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, 'mmi_check.cpp'), 'w') as f:
    f.write('// generated by tools/mmi_check.py\n')
    f.write('#include "ps2_runtime.h"\n#include "ps2_runtime_macros.h"\n#include <cstdio>\n#include <random>\n\n')
    f.write('namespace pal {\n#define __attribute__(x)\n')
    f.write('typedef union { uint64_t ud[2]; int64_t sd[2]; uint32_t uw[4]; int32_t sw[4]; uint16_t uh[8]; int16_t sh[8];'
            ' uint8_t ub[16]; int8_t sb[16]; float f[4]; } r128;\n')
    f.write('struct Ctx { r128 r[32]; r128 hi, lo; uint64_t sa; };\n')
    # GCC builtin and two helpers from the PAL port's ps2.h that mmi.h uses
    f.write('static inline int __builtin_clz(unsigned x) { unsigned long i; _BitScanReverse(&i, x); return 31 - (int)i; }\n')
    ps2h = open(os.path.join(pal_dir, 'port', 'include', 'ps2.h')).read()
    for fn in ('op_div', 'op_divu'):
        m = re.search(r'static inline void ' + fn + r'\(Ctx \*c.*?\n}\n', ps2h, re.S)
        if m:
            f.write(m.group(0))
    f.write(pal_mmi.replace('#pragma once', ''))
    f.write('\n#undef __attribute__\n}\n\n')
    f.write('static void toPal(const R5900Context *ctx, pal::Ctx *c) {\n'
            '    for (int i = 0; i < 32; ++i) std::memcpy(&c->r[i], &ctx->r[i], 16);\n'
            '    c->lo.ud[0] = ctx->lo; c->lo.ud[1] = ctx->lo1; c->hi.ud[0] = ctx->hi; c->hi.ud[1] = ctx->hi1; c->sa = ctx->sa >> 3; /* ours counts bits (MTSAB: bytes * 8), PAL bytes */\n}\n\n')
    f.write('int main() {\n    std::mt19937_64 rng(1234);\n    int failures = 0;\n')
    f.write('    alignas(16) static R5900Context ctxStore; R5900Context *ctx = &ctxStore; uint8_t *rdram = nullptr; PS2Runtime *runtime = nullptr;\n'
            '    (void)rdram; (void)runtime;\n')
    for name, (raw, body, _) in sorted(samples.items()):
        rs, rt, rd = (raw >> 21) & 31, (raw >> 16) & 31, (raw >> 11) & 31
        f.write('    {\n        int bad = 0; const char *what = "";\n')
        f.write('        for (int iter = 0; iter < 4000 && !bad; ++iter) {\n')
        f.write('            std::memset(ctx, 0, sizeof(*ctx));\n')
        f.write('            for (int i = 1; i < 32; ++i) { uint64_t a = rng(), b = rng();'
                ' if (iter & 1) { a &= 0x00ff00ff00ff00ffull; b &= 0x8000800080008000ull | 0x00ff00ff00ff00ffull; }'
                ' ctx->r[i] = _mm_set_epi64x((long long)b, (long long)a); }\n')
        f.write('            ctx->lo = rng(); ctx->lo1 = rng(); ctx->hi = rng(); ctx->hi1 = rng(); ctx->sa = (uint32_t)(rng() & 15) << 3;\n')
        f.write('            pal::Ctx ref; toPal(ctx, &ref);\n')
        f.write('            ' + body.replace('\n', '\n            ') + '\n')
        f.write('            pal::mmi_%s(&ref, %d, %d, %d);\n' % (name, rd, rs, rt))
        f.write('            pal::Ctx got; toPal(ctx, &got);\n')
        f.write('            if (std::memcmp(got.r, ref.r, sizeof ref.r)) { bad = 1; what = "rd"; }\n')
        f.write('            else if (std::memcmp(&got.lo, &ref.lo, 16) || std::memcmp(&got.hi, &ref.hi, 16)) { bad = 1; what = "HI/LO"; }\n')
        f.write('            if (bad) {\n')
        f.write('                std::printf("MISMATCH %s (%s) %%s\\n", what);\n' % (name, 'rs=%d rt=%d rd=%d' % (rs, rt, rd)))
        f.write('                for (int r : {%d, %d, %d}) std::printf("   r%%-2d got %%016llx%%016llx ref %%016llx%%016llx\\n", r,'
                ' (unsigned long long)got.r[r].ud[1], (unsigned long long)got.r[r].ud[0], (unsigned long long)ref.r[r].ud[1], (unsigned long long)ref.r[r].ud[0]);\n' % (rd, rs, rt))
        f.write('                std::printf("   lo got %%016llx%%016llx ref %%016llx%%016llx  hi got %%016llx%%016llx ref %%016llx%%016llx\\n",'
                ' (unsigned long long)got.lo.ud[1], (unsigned long long)got.lo.ud[0], (unsigned long long)ref.lo.ud[1], (unsigned long long)ref.lo.ud[0],'
                ' (unsigned long long)got.hi.ud[1], (unsigned long long)got.hi.ud[0], (unsigned long long)ref.hi.ud[1], (unsigned long long)ref.hi.ud[0]);\n')
        f.write('            }\n        }\n')
        f.write('        if (bad) ++failures; else std::printf("ok       %s\\n");\n    }\n' % name)
    f.write('    std::printf("%d of %d MMI instructions differ\\n", failures, ' + str(len(samples)) + ');\n    return failures;\n}\n')
print('%d MMI mnemonics sampled: %s' % (len(samples), ' '.join(sorted(samples))))
print('PAL defines but the game does not use: ' + ' '.join(sorted(pal_ops - set(samples))))
